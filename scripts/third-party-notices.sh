#!/bin/bash
# Writes THIRD_PARTY_NOTICES: every crate that ships in an Isocast build on
# Apple silicon (normal and build dependencies of the workspace, not
# dev-dependencies), with its licence and a link, plus the notices for the
# things bundled outside Cargo (fonts, the web app's vendored scripts) and
# Slint's royalty-free licence.
#
#   scripts/third-party-notices.sh            # rewrite THIRD_PARTY_NOTICES
#   scripts/third-party-notices.sh --check    # fail if it is out of date
#
# Needs cargo and python3. Run it after changing dependencies.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
out="$here/THIRD_PARTY_NOTICES"
check=0
[ "${1:-}" = "--check" ] && check=1

metadata="$(mktemp "${TMPDIR:-/tmp}/isocast-metadata.XXXXXX")"
generated="$(mktemp "${TMPDIR:-/tmp}/isocast-notices.XXXXXX")"
trap 'rm -f "${metadata:?}" "${generated:?}"' EXIT

cargo metadata --manifest-path "$here/Cargo.toml" --format-version 1 --locked \
    --filter-platform aarch64-apple-darwin >"$metadata"

python3 - "$metadata" "$here" >"$generated" <<'PY'
import json
import sys
from pathlib import Path

metadata = json.load(open(sys.argv[1]))
root = Path(sys.argv[2])
packages = {p["id"]: p for p in metadata["packages"]}
nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
members = set(metadata["workspace_members"])

# Walk normal and build dependencies from every workspace member;
# dev-dependencies (tests, benchmarks) never ship.
shipped = set()
stack = list(members)
while stack:
    node = nodes[stack.pop()]
    for dep in node["deps"]:
        kinds = {k["kind"] for k in dep["dep_kinds"]}
        if kinds <= {"dev"}:
            continue
        if dep["pkg"] not in shipped:
            shipped.add(dep["pkg"])
            stack.append(dep["pkg"])
shipped -= members

def link(p):
    for key in ("repository", "homepage"):
        if p.get(key):
            return p[key]
    return f"https://crates.io/crates/{p['name']}"

rows = sorted(
    (p["name"], p["version"], p.get("license") or "see " + (p.get("license_file") or "the crate"), link(p))
    for p in (packages[i] for i in shipped)
)

def section(title):
    print()
    print(title)
    print("=" * len(title))
    print()

print("THIRD-PARTY NOTICES")
print()
print("Isocast is licensed under MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE).")
print("It includes the third-party software below, under the licences shown.")
print("This file is generated by scripts/third-party-notices.sh; do not edit it")
print("by hand.")

section("Slint")
print("""The Isocast app's user interface is built with Slint (https://slint.dev),
used under the Slint Royalty-free Desktop, Mobile, and Web Applications
License v2.0 (https://slint.dev/terms-and-conditions#royalty-free). As that
licence asks, the app shows the "About Slint" notice in Help > About
Isocast. Slint's crates are listed below with their licence expressions.""")

section("Fonts")
fonts = [
    ("Instrument Sans (Regular, SemiBold)", "crates/isocast-ui/ui/fonts/LICENSE-instrument-sans"),
    ("Instrument Sans (web app, latin and latin-ext)", "crates/isocast-app/ui/vendor/LICENSE-instrument-sans"),
]
for name, path in fonts:
    print(f"- {name}: SIL Open Font License 1.1, see {path}")
print("  https://github.com/Instrument/instrument-sans")

section("Bundled scripts (the web app)")
scripts = [
    ("Preact and Preact hooks", "MIT", "crates/isocast-app/ui/vendor/LICENSE-preact", "https://github.com/preactjs/preact"),
    ("htm", "Apache-2.0", "crates/isocast-app/ui/vendor/LICENSE-htm", "https://github.com/developit/htm"),
    ("Lucide icons", "ISC", "crates/isocast-app/ui/vendor/LICENSE-lucide", "https://github.com/lucide-icons/lucide"),
]
for name, licence, path, url in scripts:
    print(f"- {name}: {licence}, see {path}")
    print(f"  {url}")

section("WebAssembly runtime")
print("""WebAssembly plugins run in Wasmtime (https://wasmtime.dev) from the
Bytecode Alliance, licensed under Apache-2.0 WITH LLVM-exception. Its crates
(wasmtime, cranelift-*, wasmparser, wit-*, ...) are listed below.""")

section(f"Rust crates ({len(rows)})")
print("Crate, version, licence, link.")
print()
for name, version, licence, url in rows:
    print(f"{name} {version}")
    print(f"  {licence}")
    print(f"  {url}")

for path in [root / "LICENSE-MIT", root / "LICENSE-APACHE"]:
    assert path.exists(), path
PY

if [ "$check" = 1 ]; then
    if ! cmp -s "$generated" "$out"; then
        echo "THIRD_PARTY_NOTICES is out of date: run scripts/third-party-notices.sh" >&2
        exit 1
    fi
    echo "THIRD_PARTY_NOTICES is up to date"
else
    cat "$generated" >"$out"
    echo "wrote $out ($(grep -c '^  http' "$out") links)"
fi
