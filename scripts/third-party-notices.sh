#!/bin/bash
# Writes THIRD_PARTY_NOTICES: every crate that ships in an Isocast build for
# any of its targets (Apple silicon macOS, x86_64 Linux and x86_64 Windows:
# the union of normal and build dependencies of the workspace on each, not
# dev-dependencies, and not the retired web app, isocast-app, which no
# longer ships since N.3), with its licence and a link, plus the notices
# for the things bundled outside Cargo (the app's fonts, native codecs) and
# Slint's royalty-free licence. Licence files of bundled native code are
# read from the pinned crates' sources that Cargo metadata points at.
#
#   scripts/third-party-notices.sh            # rewrite THIRD_PARTY_NOTICES
#   scripts/third-party-notices.sh --check    # fail if it is out of date
#
# Needs cargo and python3. Run it after changing dependencies.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
out="$here/THIRD_PARTY_NOTICES"
check=0
[ "${1:-}" = "--check" ] && check=1

# Every target Isocast ships for; a dependency of any of them is listed.
targets=(aarch64-apple-darwin x86_64-unknown-linux-gnu x86_64-pc-windows-msvc)

scratch="$(mktemp -d "${TMPDIR:-/tmp}/isocast-notices.XXXXXX")"
generated="$scratch/THIRD_PARTY_NOTICES"
trap 'rm -rf "${scratch:?}"' EXIT

for target in "${targets[@]}"; do
    cargo metadata --manifest-path "$here/Cargo.toml" --format-version 1 --locked \
        --filter-platform "$target" >"$scratch/metadata-$target.json"
done

python3 - "$here" "$scratch"/metadata-*.json >"$generated" <<'PY'
import json
import sys
from pathlib import Path

root = Path(sys.argv[1])
metadatas = [json.load(open(path)) for path in sys.argv[2:]]
assert len(metadatas) == 3, sys.argv[2:]
packages = {p["id"]: p for m in metadatas for p in m["packages"]}
members = set(metadatas[0]["workspace_members"])
# The retired web app's crate stays in the workspace until the alpha week
# is over, but nothing of it ships.
retired = {"isocast-app"}
roots = {m for m in members if packages[m]["name"] not in retired}

# Walk normal and build dependencies from every workspace member, once per
# target's resolve; dev-dependencies (tests, benchmarks) never ship.
shipped = set()
for metadata in metadatas:
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    seen = set(roots)
    stack = list(roots)
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"}:
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    shipped |= seen
shipped -= members

def source(name):
    """The source folder of the one shipped crate called name."""
    found = [packages[i] for i in shipped if packages[i]["name"] == name]
    assert len(found) == 1, (name, [p["version"] for p in found])
    return found[0], Path(found[0]["manifest_path"]).parent

def link(p):
    for key in ("repository", "homepage"):
        if p.get(key):
            return p[key]
    return f"https://crates.io/crates/{p['name']}"

rows = sorted(
    (p["name"], p["version"], p.get("license") or "see " + (p.get("license_file") or "the crate"), link(p))
    for p in (packages[i] for i in shipped)
)

def section(title):
    print()
    print(title)
    print("=" * len(title))
    print()

print("THIRD-PARTY NOTICES")
print()
print("Isocast is licensed under MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE).")
print("It includes the third-party software below, under the licences shown.")
print("This file is generated by scripts/third-party-notices.sh; do not edit it")
print("by hand.")

section("Slint")
print("""The Isocast app's user interface is built with Slint (https://slint.dev),
used under the Slint Royalty-free Desktop, Mobile, and Web Applications
License v2.0 (https://slint.dev/terms-and-conditions#royalty-free). As that
licence asks, the app shows the "About Slint" notice in Help > About
Isocast. Slint's crates are listed below with their licence expressions.""")

section("Fonts")
fonts = [
    ("Mona Sans (Light, Regular, Medium, SemiBold)", "crates/isocast-ui/ui/fonts/LICENSE-mona-sans", "https://github.com/github/mona-sans"),
    ("Hubot Sans (Medium)", "crates/isocast-ui/ui/fonts/LICENSE-hubot-sans", "https://github.com/github/hubot-sans"),
    ("Martian Mono (ExtraLight)", "crates/isocast-ui/ui/fonts/LICENSE-martian-mono", "https://github.com/evilmartians/mono"),
]
for name, path, url in fonts:
    assert (root / path).exists(), path
    print(f"- {name}: SIL Open Font License 1.1, see {path}")
    print(f"  {url}")

print("\nLinux and Windows text sources embed the same four Mona Sans faces as the app.")
print("\n".join(line.rstrip() for line in (root / "crates/isocast-ui/ui/fonts/LICENSE-mona-sans").read_text().splitlines()))

section("WebAssembly runtime")
print("""WebAssembly plugins run in Wasmtime (https://wasmtime.dev) from the
Bytecode Alliance, licensed under Apache-2.0 WITH LLVM-exception. Its crates
(wasmtime, cranelift-*, wasmparser, wit-*, ...) are listed below.""")

section("Self-update")
print("""Released copies of the app update themselves with Sparkle 2.10.0
(https://sparkle-project.org), embedded as Contents/Frameworks/Sparkle.framework
and downloaded at a pinned version and SHA-256 by scripts/sparkle/sparkle.sh.
Sparkle is under the MIT License (Copyright (c) 2006-2013 Andy Matuschak and
its other authors) and includes bsdiff 4.3 (BSD 2-clause, Colin Percival),
sais-lite (MIT, Yuta Mori) and orlp/ed25519 (zlib, Orson Peters). The full
texts ship in the app as Contents/Resources/LICENSE-Sparkle and are at
https://github.com/sparkle-project/Sparkle/blob/2.10.0/LICENSE.""")

section("VP8 decoder")
vpx = root / "crates/isocast-vp8/libvpx"
print("""VP8 video in WebM and Matroska files is decoded with libvpx's VP8 decoder
(libvpx 1.17.0, https://chromium.googlesource.com/webm/libvpx), whose sources
are vendored in crates/isocast-vp8/libvpx and built into the engine. libvpx
is under the BSD 3-clause licence below, with the WebM Project's patent
grant after it.
""")
print((vpx / "LICENSE").read_text().rstrip())
print()
print((vpx / "PATENTS").read_text().rstrip())

section("NVIDIA encoder interface")
print("""The Windows and Linux encoders use NVIDIA's public NVENC API header, vendored from
nv-codec-headers n13.0.19.0 (API 13.0):
https://github.com/FFmpeg/nv-codec-headers/blob/n13.0.19.0/include/ffnvcodec/nvEncodeAPI.h
Only the interface header is bundled. NVIDIA's driver is loaded from the
operating system, not redistributed with Isocast.
""")
header = root / "crates/isocast-platform-windows/native/nvEncodeAPI.h"
notice = header.read_text().split("*/", 1)[0].splitlines()[1:]
print("\n".join(line.removeprefix(" *").removeprefix(" ") for line in notice).strip())

section("System libraries")
print("""The Linux build links dynamically to libraries of the system it runs on;
they are not distributed with Isocast:
- GStreamer 1.x (https://gstreamer.freedesktop.org), LGPL-2.1-or-later, decodes
  media file sources. Isocast uses the distribution's own copy and the codec
  plugins (such as gstreamer1.0-libav) it loads; their source is available
  from the distribution or https://gitlab.freedesktop.org/gstreamer/gstreamer.
- PipeWire (https://pipewire.org), MIT, for screen, camera and audio capture
  and audio monitoring.""")

section("Opus encoder")
print("Program WebRTC audio uses libopus (https://opus-codec.org), bundled by libopus_sys.")
opus = next(p for p in packages.values() if p["name"] == "libopus_sys")
print((Path(opus["manifest_path"]).parent / "opus" / "COPYING").read_text().rstrip())

section("H.264 codec")
print("""Isocast contains no OpenH264. On Linux, its installer (install.sh,
which runs on the user's computer) downloads Cisco's OpenH264 2.6.0 binary
from https://ciscobinary.openh264.org, and the Linux engine (H.264 encoding)
and app (preview decoding) load it at run time. `install.sh --remove-openh264`
turns it off and `install.sh --openh264` on again. It is Cisco's binary, under
Cisco's licence, reproduced in full below (packaging/linux/CISCO_H264_LICENSE.txt,
https://www.openh264.org/BINARY_LICENSE.txt v1.0).

OpenH264 Video Codec provided by Cisco Systems, Inc.
""")
print((root / "packaging/linux/CISCO_H264_LICENSE.txt").read_text().rstrip())

section("AAC encoder")
xaac_sys, xaac_dir = source("libxaac-sys")
xaac, _ = source("xaac-rs")
print(f"""The Linux server encodes AAC-LC with libxaac
(https://github.com/ittiam-systems/libxaac), compiled from the sources
bundled in libxaac-sys {xaac_sys["version"]} and used through xaac-rs {xaac["version"]}
(vendored in vendor/xaac-rs, see its ISOCAST.md), all under the Apache
License 2.0. libxaac's NOTICE and its copy of the licence follow.
""")
print((xaac_dir / "libxaac" / "NOTICE").read_text().rstrip())
print()
print((xaac_dir / "libxaac" / "LICENSE").read_text().rstrip())

section(f"Rust crates ({len(rows)})")
print("Crate, version, licence, link.")
print()
for name, version, licence, url in rows:
    print(f"{name} {version}")
    print(f"  {licence}")
    print(f"  {url}")

for path in [root / "LICENSE-MIT", root / "LICENSE-APACHE"]:
    assert path.exists(), path
PY

if [ "$check" = 1 ]; then
    if ! cmp -s "$generated" "$out"; then
        echo "THIRD_PARTY_NOTICES is out of date: run scripts/third-party-notices.sh" >&2
        exit 1
    fi
    echo "THIRD_PARTY_NOTICES is up to date"
else
    cat "$generated" >"$out"
    echo "wrote $out ($(grep -c '^  http' "$out") links)"
fi
