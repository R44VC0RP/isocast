#!/usr/bin/env python3
"""Writes the generated reference docs from a built `isocast`:

  docs/cli.md              every command's own --help
  docs/setup-reference.md  `isocast setup schema`, as tables
  docs/mcp-tools.md        the tools `isocast mcp` serves
  docs/openrpc.json        `isocast api spec --json`, the method table as OpenRPC

    cargo build --release -p isocast-cli
    scripts/reference-docs.py [path/to/isocast]     # default target/release/isocast
    scripts/reference-docs.py --check [path]        # fail if the docs are out of date

The MCP listing runs `isocast mcp` against a throwaway socket, so it never
touches a running engine.
"""

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- Generated by scripts/reference-docs.py from the isocast binary; do not edit. -->"


def run(binary, *args, env=None):
    return subprocess.run([binary, *args], check=True, capture_output=True, text=True, env=env).stdout


# ---------------------------------------------------------------- CLI


def subcommands(help_text):
    names, inside = [], False
    for line in help_text.splitlines():
        if line.startswith("Commands:"):
            inside = True
            continue
        if inside:
            if not line.startswith("  "):
                break
            match = re.match(r"^  ([a-z][a-z0-9-]*)(\s|$)", line)
            if match and match.group(1) != "help":
                names.append(match.group(1))
    return names


def cli_doc(binary):
    out = [
        "# CLI reference",
        "",
        GENERATED,
        "",
        "Every command that prints data takes `--json`. The same methods are on",
        "the API and in MCP ([mcp-tools.md](mcp-tools.md)).",
        "",
    ]
    commands = []

    def walk(path):
        text = run(binary, *path, "--help")
        commands.append((path, text))
        for name in subcommands(text):
            walk(path + [name])

    walk([])
    out.append("## Commands")
    out.append("")
    for path, _ in commands[1:]:
        name = " ".join(path)
        out.append(f"{'  ' * (len(path) - 1)}- [`isocast {name}`](#{anchor('isocast ' + name)})")
    out.append("")
    for path, text in commands:
        title = " ".join(["isocast", *path])
        out.append(f"## {title}")
        out.append("")
        out.append("```text")
        out.append(text.rstrip())
        out.append("```")
        out.append("")
    return "\n".join(out)


def anchor(title):
    return re.sub(r"[^a-z0-9 _-]", "", title.lower()).replace(" ", "-")


# ---------------------------------------------------------------- setup schema


def one_line(text):
    return " ".join((text or "").split()).replace("|", "\\|")


def type_of(node, defs):
    if node is True or node == {}:
        return "any"
    if "$ref" in node:
        name = node["$ref"].split("/")[-1]
        base = f"[{name}](#{name.lower()})"
        if "properties" in node and "kind" in node["properties"]:
            return base
        return base
    if "const" in node:
        return f"`{json.dumps(node['const'])}`"
    if "enum" in node:
        return " \\| ".join(f"`{json.dumps(v)}`" for v in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [type_of(n, defs) for n in node[key]]
            parts = [p for p in parts if p not in ("`null`", "null")]
            optional = any(n.get("type") == "null" for n in node[key] if isinstance(n, dict))
            text = " or ".join(dict.fromkeys(parts))
            return text + (" (optional)" if optional else "")
    kind = node.get("type")
    if isinstance(kind, list):
        kinds = [k for k in kind if k != "null"]
        text = " or ".join(type_of({**node, "type": k}, defs) for k in kinds)
        return text + (" (optional)" if "null" in kind else "")
    if kind == "array":
        return f"list of {type_of(node.get('items', {}), defs)}"
    if kind == "object" and "additionalProperties" in node and isinstance(node["additionalProperties"], dict):
        return f"map of {type_of(node['additionalProperties'], defs)}"
    if kind == "integer":
        return "integer"
    return kind or "any"


def details(node):
    bits = []
    if "default" in node:
        bits.append(f"Default `{json.dumps(node['default'])}`.")
    for key, word in (("minimum", "min"), ("maximum", "max")):
        if key in node and not (key == "minimum" and node[key] == 0):
            bits.append(f"{word.capitalize()} {node[key]}.")
    return " ".join(bits)


def props_table(props, required, defs):
    rows = ["| Field | Type | Description |", "|---|---|---|"]
    for name, node in props.items():
        mark = " (required)" if name in required else ""
        desc = one_line(node.get("description", "") if isinstance(node, dict) else "")
        extra = details(node) if isinstance(node, dict) else ""
        rows.append(f"| `{name}`{mark} | {type_of(node, defs)} | {desc} {extra}".rstrip() + " |")
    return rows


def variants(node, defs):
    out = []
    for variant in node.get("oneOf", []) + node.get("anyOf", []):
        if not isinstance(variant, dict):
            continue
        tag = next(
            (
                (k, v["const"])
                for k, v in variant.get("properties", {}).items()
                if isinstance(v, dict) and "const" in v
            ),
            None,
        )
        desc = one_line(variant.get("description", ""))
        if tag and "$ref" in variant:
            out.append(f"- `{tag[0]} = {json.dumps(tag[1])}`: {type_of({'$ref': variant['$ref']}, defs)} {desc}".rstrip())
        elif tag:
            others = {k: v for k, v in variant.get("properties", {}).items() if k != tag[0]}
            line = f"- `{tag[0]} = {json.dumps(tag[1])}`"
            if others:
                line += " with " + ", ".join(f"`{k}` ({type_of(v, defs)})" for k, v in others.items())
            out.append(f"{line}. {desc}".rstrip())
        elif "const" in variant or "enum" in variant:
            out.append(f"- {type_of(variant, defs)}: {desc}".rstrip(": "))
        else:
            out.append(f"- {type_of(variant, defs)}{': ' + desc if desc else ''}")
    return out


def schema_doc(binary):
    schema = json.loads(run(binary, "setup", "schema"))
    defs = schema["$defs"]
    out = [
        "# Setup reference",
        "",
        GENERATED,
        "",
        "A setup is one document: sources, scenes, the canvas, recording and",
        "streaming settings. Write it as TOML (or JSON); `isocast setup check FILE`",
        "validates it, `isocast plan` and `isocast apply` change the live one, and",
        "`isocast setup schema` prints the JSON Schema these tables come from.",
        "Everything is addressed by `id`. The stream key is never part of a setup.",
        "",
        "## Setup",
        "",
        one_line(schema.get("description", "")),
        "",
        *props_table(schema["properties"], schema.get("required", []), defs),
        "",
    ]
    # Definitions in the order they are first referenced, from the top down.
    order, seen = [], set()

    def visit(node):
        if isinstance(node, dict):
            if "$ref" in node:
                name = node["$ref"].split("/")[-1]
                if name not in seen:
                    seen.add(name)
                    order.append(name)
                    visit(defs[name])
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)

    visit(schema["properties"])
    order += sorted(set(defs) - seen)
    for name in order:
        node = defs[name]
        out.append(f"## {name}")
        out.append("")
        if node.get("description"):
            out.append(one_line(node["description"]))
            out.append("")
        if "enum" in node:
            out.append("One of: " + ", ".join(f"`{json.dumps(v)}`" for v in node["enum"]) + ".")
            out.append("")
        if node.get("type") and "properties" not in node and "enum" not in node and not node.get("oneOf") and not node.get("anyOf"):
            out.append(f"Type: {type_of(node, defs)}.")
            out.append("")
        if node.get("properties"):
            out.extend(props_table(node["properties"], node.get("required", []), defs))
            out.append("")
        lines = variants(node, defs)
        if lines:
            tagged = any(" = " in line for line in lines)
            out.append("Plus one of these, chosen by its tag:" if tagged and node.get("properties") else "One of:")
            out.append("")
            out.extend(lines)
            out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- MCP


def mcp_doc(binary):
    with tempfile.TemporaryDirectory() as scratch:
        env = {
            **os.environ,
            "ISOCAST_SOCKET": f"{scratch}/engine.sock",
            "ISOCAST_SETUP": f"{scratch}/setup",
            "ISOCAST_DEV_APP": f"{scratch}/none.app",
        }
        requests = [
            {"jsonrpc": "2.0", "id": 1, "method": "initialize",
             "params": {"protocolVersion": "2025-06-18", "capabilities": {},
                        "clientInfo": {"name": "reference-docs", "version": "0"}}},
            {"jsonrpc": "2.0", "method": "notifications/initialized"},
            {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
        ]
        stdin = "".join(json.dumps(r) + "\n" for r in requests)
        result = subprocess.run([binary, "mcp"], input=stdin, capture_output=True,
                                text=True, env=env, timeout=60, check=True)
    tools = next(json.loads(l)["result"]["tools"] for l in result.stdout.splitlines()
                 if l.strip() and json.loads(l).get("id") == 2)
    tools.sort(key=lambda t: t["name"])
    out = [
        "# MCP tools",
        "",
        GENERATED,
        "",
        "`isocast mcp` serves Isocast to AI agents over MCP (stdin and stdout).",
        "Each tool is a method of the same API the app and the CLI use. Add it to",
        "a client, for example:",
        "",
        "```sh",
        "claude mcp add isocast -- isocast mcp",
        "```",
        "",
        f"{len(tools)} tools. Arguments marked required must be given; ids, not names,",
        "address sources, scenes and clips. Errors name the field and list the",
        "valid options.",
        "",
    ]
    for tool in tools:
        out.append(f"## {tool['name']}")
        out.append("")
        out.append(" ".join(tool.get("description", "").split()))
        out.append("")
        schema = tool.get("inputSchema", {})
        props = schema.get("properties", {})
        if props:
            required = set(schema.get("required", []))
            out.append("| Argument | Type | Description |")
            out.append("|---|---|---|")
            for name, node in props.items():
                mark = " (required)" if name in required else ""
                kind = mcp_type(node)
                out.append(f"| `{name}`{mark} | {kind} | {one_line(node.get('description', ''))} |")
            out.append("")
    return "\n".join(out)


def mcp_type(node):
    if not isinstance(node, dict):
        return "any"
    if "enum" in node:
        return " \\| ".join(f"`{json.dumps(v)}`" for v in node["enum"])
    kind = node.get("type")
    if isinstance(kind, list):
        return " or ".join(k for k in kind if k != "null") + (" (optional)" if "null" in kind else "")
    if kind == "array":
        return f"list of {mcp_type(node.get('items', {}))}"
    if kind:
        return kind
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    for key in ("anyOf", "oneOf"):
        if key in node:
            return " or ".join(dict.fromkeys(mcp_type(n) for n in node[key] if n.get("type") != "null"))
    return "any"


# ---------------------------------------------------------------- OpenRPC


def openrpc_doc(binary):
    doc = json.loads(run(binary, "api", "spec", "--json"))
    if doc.get("openrpc") != "1.3.2" or not doc.get("methods"):
        sys.exit("isocast api spec --json: not an OpenRPC 1.3.2 document")
    return json.dumps(doc, indent=2, ensure_ascii=False)


# ---------------------------------------------------------------- main


def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    binary = args[0] if args else str(ROOT / "target/release/isocast")
    docs = {
        "docs/cli.md": cli_doc(binary),
        "docs/setup-reference.md": schema_doc(binary),
        "docs/mcp-tools.md": mcp_doc(binary),
        "docs/openrpc.json": openrpc_doc(binary),
    }
    stale = []
    for path, text in docs.items():
        target = ROOT / path
        text = text.rstrip() + "\n"
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(path)
        else:
            target.write_text(text)
            print(f"wrote {path} ({len(text.splitlines())} lines)")
    if stale:
        sys.exit("out of date: " + ", ".join(stale) + " (run scripts/reference-docs.py)")


if __name__ == "__main__":
    main()
